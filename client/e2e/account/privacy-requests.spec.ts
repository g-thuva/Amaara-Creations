import { test, expect, acceptanceApi } from '../fixtures';
import { readFile } from 'node:fs/promises';
import { fillAuthenticator } from '../staffAuth';
import { checkAccessibility } from '../accessibility';

test('account export downloads owner data and a verified email change survives fresh sign-in', async ({ page, fixture }) => {
  expect((await page.request.post(`${acceptanceApi}/api/v1/auth/login`, { data: { email: fixture.customerEmail, password: fixture.password } })).ok()).toBeTruthy();
  await page.goto('./account/security');
  await page.getByLabel('Confirm password for account export', { exact: true }).fill(fixture.password);
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download account data', exact: true }).click();
  const download = await downloaded;
  const exported = JSON.parse(await readFile((await download.path())!, 'utf8'));
  expect(exported.profile.email).toBe(fixture.customerEmail);
  expect(JSON.stringify(exported)).not.toMatch(/passwordHash|securityStamp|tokenHash/);
  const newEmail = `verified-change-${Date.now()}@example.test`;
  await page.getByLabel('New sign-in email', { exact: true }).fill(newEmail);
  await page.getByLabel('Confirm password for email change', { exact: true }).fill(fixture.password);
  await page.getByRole('button', { name: 'Send email verification token', exact: true }).click();
  await expect(page.getByLabel('Email verification token', { exact: true })).toBeVisible();
  const captured = await page.request.post(`${acceptanceApi}/__fixture/email-change`, { data: { email: newEmail } });
  expect(captured.ok()).toBeTruthy();
  await page.getByLabel('Email verification token', { exact: true }).fill((await captured.json()).token);
  await page.getByLabel('Confirm password for email change', { exact: true }).fill(fixture.password);
  await page.getByRole('button', { name: 'Verify new email', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Email Address', { exact: true }).fill(newEmail);
  await page.getByLabel('Password', { exact: true }).fill(fixture.password);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await expect(page).toHaveURL(/\/profile$/);
  await expect(page.getByLabel('Email', { exact: true })).toHaveValue(newEmail);
  expect(page.url()).not.toContain(newEmail);
});

test('customer quote and deletion-review requests receive protected staff replies without deleting records', async ({ page, browser, request }) => {
  const response = await request.post(`${acceptanceApi}/__fixture/operations`); expect(response.ok()).toBeTruthy();
  const fixture = await response.json();
  expect((await page.request.post(`${acceptanceApi}/api/v1/auth/login`, { data: { email: fixture.basic.customerEmail, password: fixture.basic.password } })).ok()).toBeTruthy();
  await page.goto('./account/requests');
  const subject = `Material review ${Date.now()}`;
  await page.getByLabel('Request subject', { exact: true }).fill(subject);
  await page.getByLabel('Request details', { exact: true }).fill('Please review the available material for this custom request.');
  await page.getByLabel('Requested quantity (optional)', { exact: true }).fill('250');
  await page.getByRole('button', { name: 'Send quote request', exact: true }).click();
  await expect(page.getByRole('heading', { name: subject, exact: true })).toBeVisible();
  await page.goto('./account/security');
  await page.getByLabel('Deletion request details', { exact: true }).fill(`Privacy review ${subject}`);
  await page.getByLabel('Confirm password for deletion review', { exact: true }).fill(fixture.basic.password);
  await page.getByRole('checkbox', { name: /I understand this submits a review request/ }).check();
  await page.getByRole('button', { name: 'Submit deletion review request', exact: true }).click();
  await expect(page.getByText(/Your deletion review request was received/)).toBeVisible();
  const staffContext = await browser.newContext(); const staff = await staffContext.newPage();
  try {
    await staff.goto('http://127.0.0.1:5179/Amaara-Creations/login');
    await staff.getByLabel('Email Address', { exact: true }).fill(fixture.superAdminEmail);
    await staff.getByLabel('Password', { exact: true }).fill(fixture.basic.password);
    await fillAuthenticator(staff);
    await staff.getByRole('button', { name: 'Sign In', exact: true }).click();
    await expect(staff).toHaveURL(/\/admin\/dashboard$/);
    await staff.goto('http://127.0.0.1:5179/Amaara-Creations/admin/quote-requests');
    const quote = staff.locator('article').filter({ has: staff.getByRole('heading', { name: subject, exact: true }) });
    await quote.getByRole('button', { name: 'Review request', exact: true }).click();
    await quote.getByRole('combobox', { name: 'Review status', exact: true }).selectOption('Responded');
    await quote.getByLabel('Customer-visible reply', { exact: true }).fill('We need to review the supplied artwork before quoting.');
    await quote.getByRole('button', { name: 'Save reply', exact: true }).click();
    await expect(staff.getByText('Customer-visible reply saved.', { exact: true })).toBeVisible();
    await staff.goto('http://127.0.0.1:5179/Amaara-Creations/admin/privacy-requests');
    const privacy = staff.locator('article').filter({ hasText: `Privacy review ${subject}` });
    await privacy.getByRole('button', { name: 'Review request', exact: true }).click();
    await privacy.getByRole('combobox', { name: 'Review status', exact: true }).selectOption('InReview');
    await privacy.getByLabel('Customer-visible reply', { exact: true }).fill('The request is under retention review. No data has been erased.');
    await privacy.getByRole('button', { name: 'Save reply', exact: true }).click();
    await expect(staff.getByText('Customer-visible reply saved.', { exact: true })).toBeVisible();
    await page.goto('./account/requests');
    await expect(page.getByText('We need to review the supplied artwork before quoting.', { exact: true })).toBeVisible();
    await expect(page.getByText('The request is under retention review. No data has been erased.', { exact: true })).toBeVisible();
    await checkAccessibility(page, 'account/requests');
    await checkAccessibility(page, 'account/security');
    await page.goto('./profile'); await expect(page.getByRole('heading', { name: 'Your profile', exact: true })).toBeVisible();
  } finally { await staffContext.close(); }
});
