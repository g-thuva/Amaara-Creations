import { test, expect, acceptanceApi } from './fixtures';
import { randomBytes } from 'node:crypto';

test('real customer lifecycle, catalogue, cart, wishlist, reviews, account and CMS', async ({ page, request, fixture }) => {
  test.setTimeout(600000);
  const productId = fixture.products[0];
  const api = `${acceptanceApi}/api/v1`;
  const email = `Storefront-smoke-${Date.now()}@example.test`;
  const password = `Qa4!${randomBytes(16).toString('hex')}`;
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const confirmationResponses: number[] = [];
  page.on('response', response => { if (response.url().endsWith('/api/v1/auth/confirm-email')) confirmationResponses.push(response.status()); });
  {
    await page.goto('./register');
    await page.getByLabel('Full Name', { exact: true }).fill('Storefront QA Customer');
    await page.getByLabel('Email Address', { exact: true }).fill(email);
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByLabel('Confirm Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Create Account', exact: true }).click();
    await expect(page).toHaveURL(/\/login$/);
    const unconfirmed = await request.post(`${api}/auth/login`, { data: { email, password } });
    expect(unconfirmed.status()).toBe(401);
    const captured = await request.post(`${acceptanceApi}/__fixture/confirmation`, { data: { email } });
    expect(captured.ok(), 'Test transport captured the actual Identity confirmation').toBeTruthy();
    const { url } = await captured.json();
    const hash = new URL(url).hash;
    await page.goto(`./${hash}`);
    await expect(page.getByRole('heading', { name: 'Email Verified' })).toBeVisible();
    expect(confirmationResponses, 'Strict Mode must confirm once without a racing failure').toEqual([200]);
  }
  await page.goto(`./products/${productId}`);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Storefront QA print 01');
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Email Address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`\\/products\\/${productId}$`));
  await page.reload(); await expect(page.getByRole('heading', { level: 1 })).toHaveText('Storefront QA print 01');
  await page.getByRole('button', { name: 'View image 2', exact: true }).click();
  await expect(page.getByRole('button', { name: 'View image 2' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByLabel('Product option').selectOption({ label: 'Large format' });
  await expect(page.locator('.s-pdp-info > .s-price')).toContainText('250.00');
  await expect(page.getByRole('button', { name: 'Contact us to order', exact: true })).toBeDisabled();
  await expect(page.getByRole('link', { name: 'Contact us to order this option.', exact: true })).toBeVisible();
  await page.getByLabel('Product option').selectOption('');
  await page.getByRole('button', { name: 'Increase quantity', exact: true }).click();
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Cart, 2 items', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save to wishlist' }).click();
  await expect(page.getByRole('button', { name: 'Saved to wishlist' })).toHaveAttribute('aria-pressed', 'true');
  await page.locator('textarea[name="comment"]').fill('A temporary QA review to verify the customer flow.');
  await page.getByRole('button', { name: 'Save review', exact: true }).click();
  await expect(page.getByText('A temporary QA review to verify the customer flow.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit review' }).click();
  await page.locator('textarea[name="comment"]').fill('Updated QA review.');
  await page.getByRole('button', { name: 'Save review', exact: true }).click();
  await expect(page.getByText('Updated QA review.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete review' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByText('Updated QA review.', { exact: true })).toHaveCount(0);
  await page.goto(`./products?categoryId=${fixture.category}`);
  await expect(page.locator('.s-product-card')).toHaveCount(12);
  await page.getByRole('button', { name: 'Next product page', exact: true }).click();
  await expect(page).toHaveURL(/page=2/); await expect(page.locator('.s-product-card')).toHaveCount(1);
  await page.getByLabel('Sort by').selectOption('price-desc');
  await expect(page).not.toHaveURL(/page=2/); await expect(page.locator('.s-product-card').first()).toContainText('Storefront QA print 13');
  await page.getByRole('searchbox', { name: 'Search products', exact: true }).fill('no-such-qa-result');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No products match those filters', exact: true })).toBeVisible();
  await page.goBack(); await expect(page.locator('.s-product-card')).toHaveCount(12);
  await page.goto('./cart');
  await expect(page.getByRole('spinbutton')).toHaveValue('2');
  await page.getByRole('button', { name: /Increase quantity for/ }).click();
  await expect(page.getByRole('spinbutton')).toHaveValue('3');
  await expect(page.getByRole('link', { name: 'Cart, 3 items', exact: true })).toBeVisible();
  await page.goto('./wishlist');
  await page.getByRole('button', { name: 'Move to cart', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Cart, 4 items', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your wishlist is empty', exact: true })).toBeVisible();
  await page.goto('./profile'); await page.getByLabel('Full name', { exact: true }).fill('Storefront QA Updated');
  await page.getByRole('button', { name: 'Save profile', exact: true }).click();
  await expect(page.getByText('Welcome, Storefront QA Updated.', { exact: true })).toBeVisible();
  await page.goto('./addresses'); await page.getByRole('button', { name: 'Add an address' }).click();
  await page.getByLabel('Recipient name *', { exact: true }).fill('Storefront QA Customer');
  await page.getByLabel('Address line 1 *', { exact: true }).fill('Temporary verification address');
  await page.getByLabel('City *', { exact: true }).fill('Colombo');
  await page.getByRole('button', { name: 'Save address', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Label *', { exact: true }).fill('QA address');
  await page.getByRole('button', { name: 'Save address', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'QA address', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add an address', exact: true }).click();
  await page.getByLabel('Label *', { exact: true }).fill('Alternate QA address');
  await page.getByLabel('Recipient name *', { exact: true }).fill('Storefront QA Customer');
  await page.getByLabel('Address line 1 *', { exact: true }).fill('Second disposable verification address');
  await page.getByLabel('City *', { exact: true }).fill('Colombo');
  await page.getByLabel('Make this my default address', { exact: true }).check();
  await page.getByRole('button', { name: 'Save address', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Alternate QA address', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Set default', exact: true }).click();
  await expect(page.getByText('Default', { exact: true })).toBeVisible();
  await page.locator('article').filter({ has: page.getByRole('heading', { name: 'QA address', exact: true }) }).getByText('Default', { exact: true }).waitFor();
  await page.locator('article').filter({ has: page.getByRole('heading', { name: 'Alternate QA address', exact: true }) }).getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Alternate QA address', exact: true })).toHaveCount(0);
  for (const width of [375, 430, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    for (const route of ['', `products?categoryId=${fixture.category}`, `products/${productId}`, 'cart', 'profile', 'addresses', 'orders', 'checkout']) {
      await page.goto(`./${route}`); await expect(page.locator('main h1')).toBeVisible();
      await expect(page.locator('main [aria-label="Loading content"]')).toHaveCount(0);
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${route} at ${width}`).toBe(true);
    }
  }
  await page.goto(`./pages/${fixture.cmsSlug}`);
  await expect(page.getByText('Published content from the real CMS API.', { exact: true })).toBeVisible();
  await page.getByText('Is this real CMS content?', { exact: true }).click();
  await expect(page.getByText('Yes, this is a temporary verification page.', { exact: true })).toBeVisible();
  await page.goto('./checkout'); await expect(page.getByLabel('Saved address')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Your order', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Pay securely', exact: true })).toBeDisabled();
  await page.goto('./orders'); await expect(page.getByRole('heading', { name: 'Your orders', exact: true })).toBeVisible();
  await page.goto('./addresses'); await page.getByRole('button', { name: 'Delete', exact: true }).click(); await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click(); await expect(page.getByRole('heading', { name: 'No saved addresses yet' })).toBeVisible();
  await page.goto('./profile'); await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  // Full navigation must follow the completed logout, including cookie revocation.
  await expect(page).toHaveURL(/\/Amaara-Creations\/?$/);
  await page.goto('./profile');
  await expect(page).toHaveURL(/\/login/);
  await expect(page.getByRole('button', { name: 'Sign In', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
